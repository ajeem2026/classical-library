"""List what needs a human check: unsure facts, timings to check by ear, and dreams.

Usage: python -I notes_review.py   (writes data/notes_to_check.md and data/dreams_to_check.md)
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catalogue import NOTES, WORKS, album as album_of
from dreams import DREAMS
from library import ROOT

lib = json.load(open(os.path.join(ROOT, "web", "library.json")))
by_album = {w["album"]: w for w in lib["works"]}
fmt = lambda s: f"{s // 60}:{s % 60:02d}"

facts, ears = [], []
for album, spec in NOTES.items():
    if spec["work"]["unsure"]:
        facts.append(f"- **{album}** (work note): {spec['work']['unsure']}.  \n  “{spec['work']['text']}”")
    for n, notes in spec["movements"].items():
        track = by_album[album]["tracks"][n - 1]
        for x in notes:
            if x["unsure"]:
                facts.append(f"- **{album}**, {track['label']}: {x['unsure']}.  \n  “{x['text']}”")
        for shown in track["notes"]:
            if shown.get("check"):
                ears.append(f"- **{album}**, {track['label']}, at **{fmt(shown['at'])}**:  \n  “{shown['text']}”")


out = ["# History notes to check", "",
       "Generated by `tools/notes_review.py`. Fix facts in `tools/catalogue.py` (NOTES); fix a time by",
       "changing that note's `at` to `\"after:<seconds>\"`, then run `make docs`.",
       "Dream lines are in `data/dreams_to_check.md`.", "",
       f"## Facts to confirm ({len(facts)})", "", *facts, "",
       f"## Timings to check by ear ({len(ears)})", "",
       "Each was placed from the recording's loudness or a fraction of its length.", "", *ears, ""]
dest = os.path.join(ROOT, "data", "notes_to_check.md")
open(dest, "w").write("\n".join(out))
print(f"wrote {dest}: {len(facts)} facts, {len(ears)} timings")

# ---- Dreams: everything, for skimming, with the unsure lines flagged ----
words = lambda t: len(t.split())
flag = lambda l: f" ⚑ *{l['unsure']}*" if l.get("unsure") else ""
surname = {album_of(w): w["surname"] for w in WORKS}
out, unsure, long = ["# Dreams to check", "",
       "Generated by `tools/notes_review.py` from `tools/dreams.py`. ⚑ marks a claim the source did not",
       "confirm; lines without a source comment in `tools/dreams.py` voice feeling, not fact.", ""], [], []
body = []
for album, d in DREAMS.items():
    who = lambda l: "Me" if l["who"] == "me" else surname[album]
    body += [f"## {album}", "", "**Openings**", ""] + [f"- {who(l)}: {l['text']}{flag(l)}" for l in d["open"]] + [""]
    for i, q in enumerate(d["qa"], 1):
        body += [f"**Q{i}. {q['ask']}**", ""] + [f"{j}. {l['text']}{flag(l)}" for j, l in enumerate(q["answers"], 1)] + [""]
    body += ["**Closings**", ""] + [f"- {who(l)}: {l['text']}{flag(l)}" for l in d["close"]] + [""]
    lines = d["open"] + d["close"] + [a for q in d["qa"] for a in q["answers"]]
    unsure += [f"- **{album}**: {l['unsure']}.  \n  “{l['text']}”" for l in lines if l.get("unsure")]
    long += [f"- **{album}**: {l['text']}" for l in lines if words(l["text"]) >= 25]
out += [f"## Unsure ({len(unsure)})", "", *unsure, ""]
if long:
    out += [f"## Over 25 words ({len(long)})", "", *long, ""]
dest = os.path.join(ROOT, "data", "dreams_to_check.md")
open(dest, "w").write("\n".join(out + body))
print(f"wrote {dest}: {len(DREAMS)} works, {len(unsure)} unsure, {len(long)} over 25 words")
