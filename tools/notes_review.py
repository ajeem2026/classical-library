"""List the history notes that need a human check: unsure facts and timings to check by ear.

Usage: python -I notes_review.py   (writes data/notes_to_check.md)
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catalogue import DREAMS, NOTES
from library import ROOT

lib = json.load(open(os.path.join(ROOT, "web", "library.json")))
by_album = {w["album"]: w for w in lib["works"]}
fmt = lambda s: f"{s // 60}:{s % 60:02d}"

facts, ears = [], []
for album, spec in NOTES.items():
    if spec["work"]["unsure"]:
        facts.append(f"- **{album}** (work note): {spec['work']['unsure']}.  \n  “{spec['work']['text']}”")
    for n, notes in spec["movements"].items():
        track = by_album[album]["tracks"][n - 1]
        for x in notes:
            if x["unsure"]:
                facts.append(f"- **{album}**, {track['label']}: {x['unsure']}.  \n  “{x['text']}”")
        for shown in track["notes"]:
            if shown.get("check"):
                ears.append(f"- **{album}**, {track['label']}, at **{fmt(shown['at'])}**:  \n  “{shown['text']}”")

dreams = [f"- **{album}**: {l['unsure']}.  \n  “{l['text']}”"
          for album, lines in DREAMS.items() for l in lines if l["unsure"]]

out = ["# History notes to check", "",
       "Generated by `tools/notes_review.py`. Fix facts in `tools/catalogue.py` (NOTES); fix a time by",
       "changing that note's `at` to `\"after:<seconds>\"`, then run `make docs`.", "",
       f"## Facts to confirm ({len(facts)})", "", *facts, "",
       f"## Timings to check by ear ({len(ears)})", "",
       "Each was placed from the recording's loudness or a fraction of its length.", "", *ears, "",
       f"## Dream lines that go beyond the sources ({len(dreams)})", "",
       "The scenes are labelled as imagined; these composer lines are interpretation rather than fact.", "",
       *dreams, ""]
dest = os.path.join(ROOT, "data", "notes_to_check.md")
open(dest, "w").write("\n".join(out))
print(f"wrote {dest}: {len(facts)} facts, {len(ears)} timings, {len(dreams)} dream lines")
